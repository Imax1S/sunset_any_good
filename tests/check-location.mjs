import assert from 'node:assert/strict';
import * as api from '../dist/weather-api.js';
assert.equal(api.roundedLocation(-8.6474,115.1258).name,'Unknown location','unnamed coordinates must not pretend to identify a place');
assert.equal(typeof api.resolveLocationName,'function','live GPS coordinates need a place-name resolver');
const coordinates={latitude:-8.65,longitude:115.13};
let requested;
const named=await api.resolveLocationName(coordinates,{fetcher:async url=>{requested=new URL(url);return {ok:true,json:async()=>({locality:'Pererenan',city:'Badung',principalSubdivision:'Bali',countryName:'Indonesia'})};}});
assert.equal(named,'Pererenan, Bali');
assert.equal(requested.searchParams.get('latitude'),'-8.65');
assert.equal(requested.searchParams.get('longitude'),'115.13');
assert.equal(requested.searchParams.get('localityLanguage'),'en');
const nameFor=async data=>api.resolveLocationName(coordinates,{fetcher:async()=>({ok:true,json:async()=>data})});
assert.equal(await nameFor({city:'London',principalSubdivision:'England'}),'London, England');
assert.equal(await nameFor({localityName:'Paris',principalSubdivision:'Paris',countryName:'France'}),'Paris, France');
assert.equal(await nameFor({principalSubdivision:'Bali',countryName:'Indonesia'}),'Unknown location');
assert.equal(await nameFor({locality:'  ',city:' ',countryName:'Indonesia'}),'Unknown location');
assert.equal(await nameFor(null),'Unknown location');
assert.equal(await api.resolveLocationName(coordinates,{fetcher:async()=>({ok:false})}),'Unknown location');
assert.equal(await api.resolveLocationName(coordinates,{fetcher:async()=>{throw new Error('offline');}}),'Unknown location');
console.log('PASS: place names, locality/city fallback, duplicate regions, unknown names, failed geocoder and rounded coordinates.');
